"""
0G-Powered Prompt Security Reasoning Engine for Guardvane / PromptShield AI.
Provides intelligent contextual threat-modeling and reasoning on top
of PromptShield's local ML classifiers and heuristic detectors.
"""

from dataclasses import dataclass, field
from datetime import datetime, timezone
import json
import logging
import re
from typing import Any, Dict, List, Optional, Tuple

from integrations.zero_g.client import ZeroGClient, ZeroGResponse
from integrations.zero_g.sanitizer import (
    sanitize_prompt_for_inference,
    sanitize_context_data,
    SanitizedPromptResult,
)

logger = logging.getLogger("guardvane.zerog.reasoning")


@dataclass
class ZeroGReasoningResult:
    """Structured reasoning output generated by 0G Private Computer."""
    contextual_summary: str
    risk_explanations: Dict[str, str] = field(default_factory=dict)
    missing_security_requirements: List[str] = field(default_factory=list)
    intent_preservation_notes: str = ""
    justifications: List[str] = field(default_factory=list)
    remaining_risks: List[str] = field(default_factory=list)
    raw_content: str = ""
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "contextual_summary": self.contextual_summary,
            "risk_explanations": self.risk_explanations,
            "missing_security_requirements": self.missing_security_requirements,
            "intent_preservation_notes": self.intent_preservation_notes,
            "justifications": self.justifications,
            "remaining_risks": self.remaining_risks,
            "raw_content": self.raw_content,
            "metadata": self.metadata,
        }


class ZeroGReasoningEngine:
    """
    Orchestrates contextual security reasoning via 0G Private Computer.
    Grounds LLM reasoning in PromptShield's empirical ML findings,
    identifying architectural gaps while preserving developer intent.
    """

    SYSTEM_PROMPT = (
        "You are Guardvane's Security Reasoning Engine running inside 0G Private Computer. "
        "Your role is to perform intelligent architectural reasoning on top of empirical security "
        "findings generated by local ML models (adversarial injection probability, "
        "multi-label application attack surfaces, sensitive credential detections, and declared controls).\n\n"
        "STRICT GUIDELINES:\n"
        "1. DO NOT repeat, redefine, or contradict the local ML classifier findings.\n"
        "2. CONTEXTUALIZE: Explain how and why each unmitigated risk manifests specifically within the "
        "user's requested architecture and tech stack.\n"
        "3. IDENTIFY GAPS: Uncover missing defense-in-depth requirements that statistical models cannot detect "
        "(e.g., rate limiting, token expiration, secret rotation, TLS termination, audit logging).\n"
        "4. PRESERVE INTENT: Respect the user's chosen programming languages, frameworks, and functional goals. "
        "Do not arbitrarily add unneeded heavy frameworks or alter their core business logic.\n"
        "5. JUSTIFY: Provide clear, technical justifications for why each security hardening measure is needed.\n\n"
        "Output MUST be valid JSON with the following structure:\n"
        "{\n"
        '  "contextual_summary": "Comprehensive 2-3 sentence overview of security posture in this specific context.",\n'
        '  "risk_explanations": {\n'
        '    "<risk_label>": "Contextual explanation of how this risk manifests in the prompt..."\n'
        "  },\n"
        '  "missing_security_requirements": [\n'
        '    "Specific defense-in-depth requirement 1...",\n'
        '    "Specific defense-in-depth requirement 2..."\n'
        "  ],\n"
        '  "intent_preservation_notes": "Explanation of how functional requirements and tech stack are preserved.",\n'
        '  "justifications": [\n'
        '    "Rationale for hardening rule 1...",\n'
        '    "Rationale for hardening rule 2..."\n'
        "  ],\n"
        '  "remaining_risks": [\n'
        '    "Residual architectural risk 1 to monitor..."\n'
        "  ]\n"
        "}"
    )

    def __init__(self, client: Optional[ZeroGClient] = None):
        self.client = client or ZeroGClient()

    def _build_reasoning_prompt(
        self,
        sanitized_prompt: str,
        security_analysis: Dict[str, Any],
        recommendations: Optional[List[Dict[str, str]]] = None,
    ) -> str:
        """Constructs the structured reasoning payload for 0G without raw credentials."""
        prompt_sec = security_analysis.get("prompt_security") or {}
        app_risk = security_analysis.get("application_risks") or {}
        sensitive_data = security_analysis.get("sensitive_data") or {}

        detected_risks = app_risk.get("detected_risks") or []
        declared_controls = app_risk.get("declared_controls") or []
        declared_negations = app_risk.get("declared_negations") or []
        mitigated_surfaces = app_risk.get("mitigated_surfaces") or {}
        unmitigated_surfaces = app_risk.get("unmitigated_surfaces") or []

        findings_summary = {
            "prompt_security_classifier": {
                "is_malicious": prompt_sec.get("is_malicious", False),
                "malicious_probability": prompt_sec.get("malicious_probability", 0.0),
                "status": prompt_sec.get("status", "unknown"),
            },
            "application_risk_classifier": {
                "detected_active_risks": detected_risks,
                "unmitigated_attack_surfaces": unmitigated_surfaces,
                "mitigated_surfaces": mitigated_surfaces,
                "declared_security_controls": [c.get("name") for c in declared_controls if isinstance(c, dict)],
                "declared_feature_negations": [n.get("negation") for n in declared_negations if isinstance(n, dict)],
            },
            "sensitive_data_detector": {
                "detected": sensitive_data.get("detected", False),
                "finding_types": [f.get("type") for f in sensitive_data.get("findings", []) if isinstance(f, dict)],
            },
            "existing_rule_based_recommendations": sanitize_context_data(recommendations or []),
        }

        user_content = (
            "Analyze the following sanitized user prompt and PromptShield security analysis report:\n\n"
            f"=== TARGET PROMPT (SANITIZED) ===\n{sanitized_prompt}\n\n"
            f"=== PROMPTSHIELD EMPIRICAL FINDINGS ===\n{json.dumps(findings_summary, indent=2)}\n\n"
            "Provide your reasoning in the specified JSON format."
        )
        return user_content

    def _parse_reasoning_response(
        self,
        response: ZeroGResponse,
        detected_risks: List[str]
    ) -> ZeroGReasoningResult:
        """Parses the 0G response content into a structured ZeroGReasoningResult."""
        raw_text = response.content.strip()
        metadata = {
            "provider": "0g",
            "model": response.model,
            "response_id": response.response_id,
            "request_id": response.request_id,
            "trust_mode": response.trust_mode,
            "usage": response.usage or {},
            "status": "0g_success",
            "inference_used": True,
            "duration_ms": response.duration_ms,
            "is_attestation_verified": False,
        }

        # Attempt JSON extraction
        parsed_json: Optional[Dict[str, Any]] = None

        try:
            parsed_json = json.loads(raw_text)
        except json.JSONDecodeError:
            code_block_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", raw_text)
            if code_block_match:
                try:
                    parsed_json = json.loads(code_block_match.group(1).strip())
                except json.JSONDecodeError:
                    pass

        if isinstance(parsed_json, dict):
            return ZeroGReasoningResult(
                contextual_summary=str(parsed_json.get("contextual_summary", "")).strip(),
                risk_explanations=parsed_json.get("risk_explanations") or {},
                missing_security_requirements=list(parsed_json.get("missing_security_requirements") or []),
                intent_preservation_notes=str(parsed_json.get("intent_preservation_notes", "")).strip(),
                justifications=list(parsed_json.get("justifications") or []),
                remaining_risks=list(parsed_json.get("remaining_risks") or []),
                raw_content=raw_text,
                metadata=metadata,
            )

        # Fallback text parsing if model did not return strictly valid JSON
        lines = [line.strip() for line in raw_text.splitlines() if line.strip()]
        summary = lines[0] if lines else "Analysis completed by 0G Private Computer."

        return ZeroGReasoningResult(
            contextual_summary=summary,
            risk_explanations={r: f"Identified application attack surface: {r}" for r in detected_risks},
            missing_security_requirements=[
                "Explicit input boundary validation and sanitization",
                "Centralized authentication and authorization verification",
                "Defense-in-depth rate limiting and audit logging",
            ],
            intent_preservation_notes="Preserved core technical stack and business requirements.",
            justifications=["Enforce defense-in-depth principles without altering functional architecture."],
            remaining_risks=["Monitor runtime LLM inputs for novel injection payloads."],
            raw_content=raw_text,
            metadata=metadata,
        )

    def _create_local_fallback(
        self,
        security_analysis: Dict[str, Any],
        reason: str
    ) -> ZeroGReasoningResult:
        """Constructs an empirical fallback reasoning result locally without burning credits."""
        app_risk = security_analysis.get("application_risks") or {}
        detected_risks = app_risk.get("detected_risks") or []
        unmitigated = app_risk.get("unmitigated_surfaces") or []

        return ZeroGReasoningResult(
            contextual_summary=(
                f"Local analysis identified {len(detected_risks)} attack surfaces "
                f"({len(unmitigated)} unmitigated). Evaluated offline without 0G remote inference."
            ),
            risk_explanations={r: f"Local heuristic detection flagged {r}." for r in detected_risks},
            missing_security_requirements=[
                "Enforce strict input boundary validation",
                "Apply defense-in-depth rate limiting",
                "Isolate system instructions from untrusted data",
            ],
            intent_preservation_notes="Maintained user parameters using offline deterministic rules.",
            justifications=["Protect application attack boundaries without remote dependency."],
            remaining_risks=["Heuristic rules may not cover subtle contextual adversarial drift."],
            raw_content="Local fallback reasoning generated without external 0G inference.",
            metadata={
                "provider": "0g",
                "model": self.client.model,
                "request_id": None,
                "trust_mode": self.client.trust_mode,
                "status": "local_fallback",
                "inference_used": False,
                "fallback_used": True,
                "fallback_reason": reason,
                "duration_ms": 0.0,
                "is_attestation_verified": False,
            },
        )

    # -----------------------------------------------------------------------
    # Synchronous Reasoning
    # -----------------------------------------------------------------------

    def reason(
        self,
        prompt: str,
        security_analysis: Dict[str, Any],
        recommendations: Optional[List[Dict[str, str]]] = None,
        temperature: float = 0.3,
        max_tokens: Optional[int] = None,
        fallback_to_local: bool = True,
    ) -> ZeroGReasoningResult:
        """
        Executes 0G reasoning synchronously.
        Automatically sanitizes the prompt before transmitting to 0G.
        """
        if not self.client.is_enabled or not self.client.is_configured:
            if fallback_to_local:
                return self._create_local_fallback(
                    security_analysis,
                    "0G remote inference is disabled (ZG_ENABLED=false) or unconfigured."
                )
            self.client.validate_configuration()

        sanitization = sanitize_prompt_for_inference(prompt)
        user_prompt = self._build_reasoning_prompt(
            sanitization.sanitized_prompt,
            security_analysis,
            recommendations,
        )

        detected_risks = (
            (security_analysis.get("application_risks") or {}).get("detected_risks") or []
        )

        try:
            response = self.client.complete(
                prompt=user_prompt,
                system_prompt=self.SYSTEM_PROMPT,
                temperature=temperature,
                max_tokens=max_tokens,
            )
            return self._parse_reasoning_response(response, detected_risks)
        except Exception as e:
            logger.warning(f"0G reasoning failed: {e}")
            if fallback_to_local:
                return self._create_local_fallback(security_analysis, str(e))
            raise

    # -----------------------------------------------------------------------
    # Asynchronous Reasoning
    # -----------------------------------------------------------------------

    async def reason_async(
        self,
        prompt: str,
        security_analysis: Dict[str, Any],
        recommendations: Optional[List[Dict[str, str]]] = None,
        temperature: float = 0.3,
        max_tokens: Optional[int] = None,
        fallback_to_local: bool = True,
    ) -> ZeroGReasoningResult:
        """
        Executes 0G reasoning asynchronously.
        """
        if not self.client.is_enabled or not self.client.is_configured:
            if fallback_to_local:
                return self._create_local_fallback(
                    security_analysis,
                    "0G remote inference is disabled (ZG_ENABLED=false) or unconfigured."
                )
            self.client.validate_configuration()

        sanitization = sanitize_prompt_for_inference(prompt)
        user_prompt = self._build_reasoning_prompt(
            sanitization.sanitized_prompt,
            security_analysis,
            recommendations,
        )

        detected_risks = (
            (security_analysis.get("application_risks") or {}).get("detected_risks") or []
        )

        try:
            response = await self.client.complete_async(
                prompt=user_prompt,
                system_prompt=self.SYSTEM_PROMPT,
                temperature=temperature,
                max_tokens=max_tokens,
            )
            return self._parse_reasoning_response(response, detected_risks)
        except Exception as e:
            logger.warning(f"0G async reasoning failed: {e}")
            if fallback_to_local:
                return self._create_local_fallback(security_analysis, str(e))
            raise
